const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem(STORAGE_KEY) || "uk");

  const value = useMemo(() => ({
    lang,
    setLang: (next) => {
      localStorage.setItem(STORAGE_KEY, next);
      setLang(next);
    },
    t: dict[lang],
    methodLabel: (key) => methodLabels[key]?.[lang] || key,
    methodDetails: (key) => {
      const details = methodDetails[key];
      if (!details) return null;
      return {
        description: details.description[lang],
        bestFor: details.bestFor[lang],
        categories: details.categories,
      };
    },
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/**
 * @returns {{
 *   lang: string,
 *   setLang: (next: string) => void,
 *   t: Record<string, any>,
 *   methodLabel: (key: string) => string,
 *   methodDetails: (key: string) => { description: string, bestFor: string, categories: string[] } | null,
 * }}
 */
export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
